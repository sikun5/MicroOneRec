#!/usr/bin/env python
"""Phase 5 T3: paired user-cluster bootstrap with locked sampling algorithm.
SCHEMA: phase5-v2_bootstrap-1.0

LOCKED BOOTSTRAP PROTOCOL (boss spec 2026-11-11):
- seed=42, rounds=2000, numpy.random.default_rng (PCG64); ONE rng instance,
  rounds drawn sequentially -> the shared sampling list is a single
  deterministic sequence reused by ALL methods/pairs (methods never re-sample).
- Per round: draw len(unique_users) users WITH replacement, U = the evaluation
  set's ACTUAL unique-user count (never hardcoded to any fixed split's count).
- Every row of a drawn user enters the round, repeated per draw multiplicity
  (no dedup, no cap). Diff = (weighted-mean metric of method B) - (A) over the
  round's sampled rows. CI = np.percentile(valid_round_diffs, [2.5, 97.5]),
  linear interpolation, over VALID rounds only.
- Slice rounds: rows filtered by the TARGET's original-description label after
  sampling; a round with zero slice rows is marked INVALID and counted
  (n_invalid), never zero-filled.
- Training randomness is NOT covered by this bootstrap (protocol).
- Real-validation sampling lists are generated by this same function at T4/T5
  evaluation time; this module's checks are synthetic (no real predictions).

Synthetic checks B1-B6: cluster multiplicity (hand-computed), identical
predictions -> CI endpoints 0, non-zero paired diff hand case + same-seed
replay identity, empty-slice invalid counting (all-valid & all-invalid), U
varies by set (2 vs 3; source contains no hardcoded user counts), seed
sensitivity (42 vs 43 differ)."""
import argparse, json, math, hashlib
from pathlib import Path
import numpy as np

SEED = 42
ROUNDS = 2000
PCTS = (2.5, 97.5)


def sha256_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def sample_users(rng, unique_users, rounds=ROUNDS):
    """Shared sampling list: rounds lists of user ids, drawn with replacement.
    unique_users MUST be sorted (deterministic order); rng consumed sequentially."""
    users = np.array(sorted(unique_users))
    return [rng.choice(users, size=len(users), replace=True) for _ in range(rounds)]


def build_user_rows(rows, slice_label=None):
    """rows: [{user_id, metric_a, metric_b, slice}] aligned per row across methods."""
    ur = {}
    for r in rows:
        ur.setdefault(r["user_id"], []).append(
            (float(r["metric_a"]), float(r["metric_b"]), bool(r["slice"])))
    return ur


def round_diff(draw, user_rows, slice_label=None):
    """One round: row-weighted mean diff over drawn users (multiplicity kept).
    Returns (diff, n_rows) or (None, 0) when the round has no slice rows."""
    sa = sb = 0.0
    n = 0
    for u in draw:
        for ma, mb, sl in user_rows[u]:
            if slice_label is None or sl == slice_label:
                sa += ma
                sb += mb
                n += 1
    if n == 0:
        return None, 0
    return (sb - sa) / n, n


def bootstrap(rows, seed=SEED, rounds=ROUNDS, slice_label=None):
    """Full bootstrap. rows: [{user_id, metric_a, metric_b, slice}].
    Returns dict with round diffs, CI (valid rounds), valid/invalid counts."""
    users = sorted(set(r["user_id"] for r in rows))
    rng = np.random.default_rng(seed)
    draws = sample_users(rng, users, rounds)
    ur = build_user_rows(rows, slice_label)
    diffs, n_invalid = [], 0
    for draw in draws:
        d, _ = round_diff(draw, ur, slice_label)
        if d is None:
            n_invalid += 1
        else:
            diffs.append(d)
    if diffs:
        lo, hi = np.percentile(np.array(diffs), PCTS)
        ci = [float(lo), float(hi)]
    else:
        ci = None
    return {"seed": seed, "rounds": rounds, "U": len(users), "slice_label": slice_label,
            "n_valid_rounds": len(diffs), "n_invalid_rounds": n_invalid,
            "round_diffs": diffs, "ci_low": ci[0] if ci else None, "ci_high": ci[1] if ci else None,
            "ci": ci}


# ---------------- synthetic checks ----------------

def run_self_test():
    cases = []
    def rec(cid, name, got, want, ok, note="", inp=None):
        cases.append({"case": cid, "scenario": name, "input": inp or {},
                      "got": got, "expected": want, "pass": bool(ok), "note": note})
        print(f"B {cid} {name}: pass={ok}", flush=True)

    # B1 cluster multiplicity, hand-computed via forced draws + exhaustive-enumeration CI
    rows1 = [
        {"user_id": "U1", "metric_a": 1.0, "metric_b": 1.0, "slice": False},
        {"user_id": "U1", "metric_a": 0.0, "metric_b": 0.5, "slice": False},
        {"user_id": "U2", "metric_a": 0.0, "metric_b": 0.0, "slice": False},
    ]
    ur1 = build_user_rows(rows1)
    d_u1u1, n_u1u1 = round_diff(("U1", "U1"), ur1)   # U1 twice -> 4 rows
    d_u1u2, n_u1u2 = round_diff(("U1", "U2"), ur1)   # 3 rows
    d_u2u2, n_u2u2 = round_diff(("U2", "U2"), ur1)   # U2 rows only -> 1 row twice? rows enter per draw
    # exhaustive enumeration of ALL ordered outcomes (U=2, 2 draws with replacement):
    b1 = bootstrap(rows1)
    outcomes = {("U1", "U1"): 0.25, ("U1", "U2"): 1 / 6, ("U2", "U1"): 1 / 6, ("U2", "U2"): 0.0}
    # exact distribution: P(0.25)=1/4, P(1/6)=1/2, P(0)=1/4 -> with 2000 draws the
    # 2.5%/97.5% empirical percentiles land inside the 0-block / 0.25-block -> CI=[0, 0.25]
    ok1 = (abs(d_u1u1 - 0.25) < 1e-12 and n_u1u1 == 4
           and abs(d_u1u2 - (1.0 / 6.0)) < 1e-12 and n_u1u2 == 3
           and b1["ci"][0] == 0.0 and abs(b1["ci"][1] - 0.25) < 1e-12
           and b1["n_valid_rounds"] == ROUNDS)
    rec("B1", "cluster_multiplicity_hand_plus_enumerated_ci",
        {"diff_U1U1": d_u1u1, "n_U1U1": n_u1u1, "diff_U1U2": d_u1u2, "n_U1U2": n_u1u2,
         "measured_ci": b1["ci"], "exact_outcome_distribution": {str(k): v for k, v in outcomes.items()}},
        {"diff_U1U1": 0.25, "n_U1U1": 4, "diff_U1U2": 1 / 6, "n_U1U2": 3,
         "measured_ci": [0.0, 0.25],
         "exact_outcome_distribution": "independent enumeration: (U1,U1)->0.25 p=1/4; (U1,U2)/(U2,U1)->1/6 p=1/2; (U2,U2)->0 p=1/4; with 2000 draws the 2.5%/97.5% quantile positions (49.98/1949.8 in sorted array) fall inside the 0-block (first ~500) and the 0.25-block (last ~500) -> exact expectation CI=[0.0, 0.25]"},
        ok1,
        note="U1 rows (a:[1,0], b:[1,0.5]) enter TWICE when drawn twice: mean_a=(1+0+1+0)/4=0.5, mean_b=(1+0.5+1+0.5)/4=0.75 -> diff 0.25; no dedup. CI independently derived from exhaustive enumeration of all 4 ordered outcomes, matched by measured bootstrap",
        inp={"rows": rows1, "forced_draws": [["U1", "U1"], ["U1", "U2"]],
             "full_bootstrap": {"seed": 42, "rounds": 2000, "U": 2}})

    # B2 identical predictions -> all diffs 0, CI endpoints 0
    rows2 = [
        {"user_id": "U1", "metric_a": 0.8, "metric_b": 0.8, "slice": False},
        {"user_id": "U1", "metric_a": 0.2, "metric_b": 0.2, "slice": False},
        {"user_id": "U2", "metric_a": 1.0, "metric_b": 1.0, "slice": False},
    ]
    b2 = bootstrap(rows2)
    ok2 = (b2["n_invalid_rounds"] == 0 and all(d == 0.0 for d in b2["round_diffs"])
           and b2["ci"] == [0.0, 0.0] and b2["n_valid_rounds"] == ROUNDS)
    rec("B2", "identical_predictions_ci_zero", {"ci": b2["ci"], "n_valid": b2["n_valid_rounds"],
                                                "max_abs_diff": max(abs(d) for d in b2["round_diffs"])},
        {"ci": [0.0, 0.0], "n_valid": ROUNDS, "max_abs_diff": 0.0}, ok2,
        inp={"rows": rows2, "config": {"seed": 42, "rounds": 2000}})

    # B3 non-zero paired diff: replay identity + CI = percentile(replay)
    rows3 = [
        {"user_id": "U1", "metric_a": 1.0, "metric_b": 0.0, "slice": False},
        {"user_id": "U2", "metric_a": 0.0, "metric_b": 1.0, "slice": False},
        {"user_id": "U2", "metric_a": 0.5, "metric_b": 0.5, "slice": False},
    ]
    b3 = bootstrap(rows3)
    rng3 = np.random.default_rng(SEED)
    draws3 = sample_users(rng3, sorted(set(r["user_id"] for r in rows3)))
    ur3 = build_user_rows(rows3)
    replay = [round_diff(d, ur3)[0] for d in draws3]
    replay = [x for x in replay if x is not None]
    same = len(replay) == len(b3["round_diffs"]) and all(
        abs(x - y) < 1e-15 for x, y in zip(replay, b3["round_diffs"]))
    lo, hi = np.percentile(np.array(replay), PCTS)
    ok3 = same and abs(b3["ci_low"] - float(lo)) < 1e-15 and abs(b3["ci_high"] - float(hi)) < 1e-15 \
        and (max(b3["round_diffs"]) > 0 or min(b3["round_diffs"]) < 0)
    rec("B3", "nonzero_diff_replay_identity", {"replay_identical": same,
                                               "ci": b3["ci"], "n_diffs": len(b3["round_diffs"])},
        {"replay_identical": True, "ci_equals_percentile_of_replay": True, "nonzero_diffs": True}, ok3,
        note="same-seed replay reproduces every round diff bit-identically; CI=np.percentile(replay,[2.5,97.5],linear)",
        inp={"rows": rows3, "config": {"seed": 42, "rounds": 2000, "U": 2}})

    # B4 empty slice rounds: all-invalid and all-valid
    rows4n = [{"user_id": "U1", "metric_a": 1.0, "metric_b": 0.0, "slice": False}]
    b4n = bootstrap(rows4n, slice_label=True)   # no slice rows anywhere
    ok4n = b4n["n_invalid_rounds"] == ROUNDS and b4n["n_valid_rounds"] == 0 and b4n["ci"] is None
    rec("B4a", "empty_slice_all_invalid", {"n_valid": b4n["n_valid_rounds"],
                                           "n_invalid": b4n["n_invalid_rounds"], "ci": b4n["ci"]},
        {"n_valid": 0, "n_invalid": ROUNDS, "ci": None}, ok4n,
        note="no slice rows in any round -> marked invalid and counted, never zero-filled",
        inp={"rows": rows4n, "slice_label": True})
    rows4v = [{"user_id": "U1", "metric_a": 1.0, "metric_b": 0.0, "slice": True}]
    b4v = bootstrap(rows4v, slice_label=True)
    ok4v = b4v["n_valid_rounds"] == ROUNDS and b4v["n_invalid_rounds"] == 0 and b4v["ci"] == [-1.0, -1.0]
    rec("B4b", "slice_all_valid", {"n_valid": b4v["n_valid_rounds"], "n_invalid": b4v["n_invalid_rounds"],
                                   "ci": b4v["ci"]},
        {"n_valid": ROUNDS, "n_invalid": 0, "ci": [-1.0, -1.0]}, ok4v,
        note="single user with 1 slice row (a=1,b=0): every round diff=-1 -> CI [-1,-1]",
        inp={"rows": rows4v, "slice_label": True})

    # B5 U varies by evaluation set (2 vs 3); no hardcoded user counts in source
    rows5a = [{"user_id": "U1", "metric_a": 1.0, "metric_b": 0.0, "slice": False},
              {"user_id": "U2", "metric_a": 0.0, "metric_b": 1.0, "slice": False}]
    rows5b = rows5a + [{"user_id": "U3", "metric_a": 0.3, "metric_b": 0.7, "slice": False}]
    b5a, b5b = bootstrap(rows5a), bootstrap(rows5b)
    src = Path(__file__).read_text()
    bad_a = "19" + "87"   # runtime-built: the check source itself must not contain the literals
    bad_b = "20" + "11"
    ok5 = (b5a["U"] == 2 and b5b["U"] == 3 and bad_a not in src and bad_b not in src)
    rec("B5", "U_varies_no_hardcode", {"U_set1": b5a["U"], "U_set2": b5b["U"],
                                       "hardcoded_counts_in_source": False},
        {"U_set1": 2, "U_set2": 3, "hardcoded_counts_in_source": False}, ok5,
        note="draw size per round = actual U; source free of any fixed split-count literals",
        inp={"set1_U": 2, "set2_U": 3})

    # B6 seed sensitivity + shared-list determinism
    users6 = [f"X{i}" for i in range(20)]
    rows6 = [{"user_id": u, "metric_a": 0.5, "metric_b": 0.5 + (i % 3) * 0.1, "slice": False}
             for i, u in enumerate(users6)]
    d42a = sample_users(np.random.default_rng(42), users6, rounds=5)
    d42b = sample_users(np.random.default_rng(42), users6, rounds=5)
    d43 = sample_users(np.random.default_rng(43), users6, rounds=5)
    same42 = all((a == b).all() for a, b in zip(d42a, d42b))
    diff43 = any((a != c).any() for a, c in zip(d42a, d43))
    b6 = bootstrap(rows6)  # full 2000-round run consumed sequentially from one rng
    ok6 = same42 and diff43 and b6["seed"] == 42 and b6["rounds"] == ROUNDS
    rec("B6", "seed_locked_deterministic", {"replay_42_identical": same42, "seed43_differs": diff43,
                                            "config": {"seed": b6["seed"], "rounds": b6["rounds"]}},
        {"replay_42_identical": True, "seed43_differs": True, "config": {"seed": 42, "rounds": 2000}}, ok6,
        note="rng= default_rng (PCG64); one instance consumed round-by-round -> shared list reproducible & method-shared",
        inp={"U": 20, "rounds_probe": 5})

    # B7 mixed slice rounds: 0 < n_invalid < ROUNDS; valid-round CI over slice rows only
    rows7 = [
        {"user_id": "U1", "metric_a": 1.0, "metric_b": 0.0, "slice": True},    # slice user
        {"user_id": "U1", "metric_a": 0.5, "metric_b": 0.5, "slice": True},    # slice user (2nd row)
        {"user_id": "U2", "metric_a": 0.0, "metric_b": 1.0, "slice": False},   # non-slice user
    ]
    b7 = bootstrap(rows7, slice_label=True)
    # independent recomputation of every valid round by straightforward replay
    rng7 = np.random.default_rng(SEED)
    draws7 = sample_users(rng7, sorted(set(r["user_id"] for r in rows7)))
    ur7 = build_user_rows(rows7)
    valid_expected, n_invalid_expected = [], 0
    for draw in draws7:
        d, n = round_diff(draw, ur7, slice_label=True)
        if d is None:
            n_invalid_expected += 1
        else:
            valid_expected.append(d)
    same7 = (len(valid_expected) == len(b7["round_diffs"]) and n_invalid_expected == b7["n_invalid_rounds"]
             and all(abs(x - y) < 1e-15 for x, y in zip(valid_expected, b7["round_diffs"])))
    mixed = 0 < b7["n_invalid_rounds"] < ROUNDS
    # slice rows only from U1 (diff=(0-1)/2=-0.5 or (0.5-0.5)/2=0): valid diffs must be in {-0.5, 0.0}
    vals_ok = all(d in (-0.5, 0.0) for d in b7["round_diffs"])
    ok7 = mixed and same7 and vals_ok and b7["n_valid_rounds"] + b7["n_invalid_rounds"] == ROUNDS
    rec("B7", "mixed_slice_rounds", {"n_valid": b7["n_valid_rounds"], "n_invalid": b7["n_invalid_rounds"],
                                     "ci": b7["ci"], "replay_match": same7, "valid_diff_values_only_-0.5_0": vals_ok},
        {"mixed": "0 < n_invalid < 2000", "replay_match": True, "valid_diff_values_only_-0.5_0": True}, ok7,
        note="post-sampling filtering by target slice label; rounds whose drawn users contain no slice rows are marked invalid and counted (never zero-filled); CI computed over valid rounds only",
        inp={"rows": rows7, "slice_label": True, "seed": 42, "rounds": 2000, "U": 2})

    # B8 manual percentile formula (hand) == np.percentile, independent of bootstrap replay
    def manual_percentile(sorted_vals, q):
        n = len(sorted_vals)
        pos = (n - 1) * q / 100.0
        lo, hi = int(math.floor(pos)), int(math.ceil(pos))
        frac = pos - lo
        return sorted_vals[lo] * (1 - frac) + sorted_vals[hi] * frac
    probes = [
        (list(range(1, 101)), PCTS),                # n=100 even
        (list(range(0, 2000)), PCTS),               # n=2000 even
        ([0.0] * 500 + [1 / 6] * 1000 + [0.25] * 500, PCTS),  # B1-style block array
        ([2.0, 4.0, 4.0, 5.0, 6.0], (25.0, 75.0)),  # n=5 odd, fractional positions
    ]
    ok8, m8 = True, []
    for vals, qs in probes:
        sv = sorted(vals)
        for q in qs:
            man, npq = manual_percentile(sv, q), float(np.percentile(np.array(vals), q))
            m8.append({"n": len(vals), "q": q, "manual": man, "numpy": npq,
                       "abs_diff": abs(man - npq)})
            ok8 &= abs(man - npq) < 1e-12
    rec("B8", "manual_percentile_formula_matches_numpy", {"probes": m8, "all_match": ok8},
        {"all_match": True}, ok8,
        note="hand formula: pos=(n-1)*q/100 linear interpolation; proves the CI quantile computation itself, independent of any replay; tolerance 1e-12 absorbs last-ulp float-path noise between two arithmetically identical formulas (observed max diff ~1e-14)",
        inp={"formula": "pos=(n-1)*q/100; interpolate floor/ceil", "n_probes": len(m8), "tolerance": 1e-12})

    all_pass = all(c["pass"] for c in cases)
    summary = {"schema": "phase5-shared-sampling-summary-1.0", "date": "2026-11-11",
               "algorithm": "numpy.random.default_rng(seed=42, PCG64); rounds x choice(unique_users_sorted, size=U, replace=True); ONE rng consumed sequentially -> single shared list reused by all methods/pairs",
               "locked": {"seed": SEED, "rounds": ROUNDS, "percentile": "np.percentile linear [2.5, 97.5] over valid rounds",
                          "U_rule": "actual unique-user count of the evaluation set, computed at run time (never a hardcoded fixed split count)"},
               "synthetic_verification": {"n_cases": len(cases), "all_pass": all_pass},
               "real_list_note": "real validation sampling lists are generated by bootstrap() at T4/T5 evaluation time from the same locked function; not generated now (no real predictions in Phase 5 synthesis)",
               "training_randomness": "not covered by bootstrap (protocol)"}
    return {"schema": "phase5-bootstrap-checks-1.0", "date": "2026-11-11",
            "n_cases": len(cases), "all_pass": all_pass, "cases": cases}, summary


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--output", type=str, default="")
    ap.add_argument("--summary-output", type=str, default="")
    args = ap.parse_args()
    if args.self_test:
        checks, summary = run_self_test()
        if args.output:
            Path(args.output).write_text(json.dumps(checks, ensure_ascii=False, indent=1))
            print("BOOTSTRAP_CHECKS_SHA256:", sha256_file(args.output), flush=True)
        if args.summary_output:
            Path(args.summary_output).write_text(json.dumps(summary, ensure_ascii=False, indent=1))
            print("SAMPLING_SUMMARY_SHA256:", sha256_file(args.summary_output), flush=True)
        print("BOOTSTRAP_ALL_PASS:", checks["all_pass"], flush=True)
        print("BOOTSTRAP_DONE", flush=True)


if __name__ == "__main__":
    main()
